# Import necessary libraries for data manipulation and analysis
import pandas as pd
import numpy as np

"""loading data"""

# Load the credit default classification dataset and preview the first 5 rows
df=pd.read_csv('/content/credit_default_classification.csv')
df.head()

# Display structural information of the dataset, including non-null counts and data types
df.info()

"""**PREPROCESSING**"""

# Handle missing values in the 'age' column using forward-fill
df['age']=df['age'].ffill()
df['age']

# Impute missing values in numeric columns ('loan_amount_k' and 'credit_score') with their respective means
df['loan_amount_k']=df['loan_amount_k'].fillna(df['loan_amount_k'].mean())
df['credit_score']=df['credit_score'].fillna(df['credit_score'].mean())

df['credit_score'].isna().sum()

# Inspect the unique values in the 'home_owner' column to check for inconsistency or formatting issues
df['home_owner'].unique()

# Standardize inconsistent categorical values in 'home_owner' to standard 'Yes' or 'No'
df['home_owner']=df['home_owner'].replace(['Ys','Yes','es','Ye','YES'],'Yes')
df['home_owner']=df['home_owner'].replace(['NO','N','o'],'No')

# Impute missing values in 'home_owner' with the column's most frequent value (mode)
df['home_owner']=df['home_owner'].fillna(df['home_owner'].mode()[0])

# Fill missing values in 'num_open_accounts' using forward-fill
df['num_open_accounts']=df['num_open_accounts'].ffill()

# Fill missing values in 'income_k' with the column's mean
df['income_k']=df['income_k'].fillna(df['income_k'].mean())

# Display the standardized categories in the 'loan_purpose' column
df['loan_purpose'].unique()

# Fill missing values in the target variable 'defaulted' with its mode
df['defaulted']=df['defaulted'].fillna(df['defaulted'].mode()[0])

# Drop the original 'customer' column to avoid issues before regenerating standard customer IDs
df=df.drop(columns='customer')

# Create a continuous, unique numeric ID sequence for the 'customer' column
df['customer']=np.arange(1,len(df)+1)
df['customer']

# Standardize variations, typos, and casings for 'loan_purpose' and impute remaining missing values with the mode
df['loan_purpose'] = df['loan_purpose'].replace(['Debt cnsolidation', 'Dbt consolidation', 'Debt consolidation','Debt consolidton','Dbt consolidtion', 'Debt consolidtion', 'Debt consolidaton',], 'DEBT CONSOLIDATION')
df['loan_purpose'] = df['loan_purpose'].replace(['Home improvemnt','Home improvement', 'Hom improvement','Home imrovement','Home imrovement','Hme improvement','Hoe improvement','ome improvement','ome improvement','Home imprvement'],'HOME IMPROVEMENT')
df['loan_purpose'] = df['loan_purpose'].replace(['Business','Busines','Buiness','Busness','Bsiness','usiness','Busiess','Businss'],'BUSINESS')
df['loan_purpose'] = df['loan_purpose'].replace(['Cr','Car','ar'],'CAR')
df['loan_purpose'] = df['loan_purpose'].replace(['ducation','Education','Educatin', 'Eduction','Educaion','Educatio', 'Edcation','Eucation'],'EDUCATION')
df['loan_purpose'] = df['loan_purpose'].fillna(df['loan_purpose'].mode()[0])

# Impute missing values in 'months_since_delinq' with the most common value (mode)
df['months_since_delinq']=df['months_since_delinq'].fillna(df['months_since_delinq'].mode()[0])

# Drop redundant duplicate column 'credit_score_dup'
df=df.drop(columns='credit_score_dup')

# Final verification of the cleaned dataset
df.head()

#storing preprocesed file into another file
df.to_csv('/content/preprosed.csv')

